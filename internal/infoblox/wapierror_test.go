// TestRecordsLogsAuthFailureWithoutRetry pins the fix for issue #50: a WAPI user
// that is rejected with 401 must produce an error-level log line naming the
// status code and the object type, and the call must not be retried.
func TestRecordsLogsAuthFailureWithoutRetry(t *testing.T) {
	hook := captureLogs(t)
	p, requests := newStubGrid(t, http.StatusUnauthorized, "401 Unauthorized")

	_, err := p.Records(context.TODO())
	require.Error(t, err)

	entry := findEntry(hook, log.ErrorLevel, WAPIFailureAuth)
	require.NotNil(t, entry, "expected an error-level log entry classified as an auth failure, got: %s", dumpEntries(hook))
	assert.Equal(t, http.StatusUnauthorized, entry.Data["http_status"])
	assert.Equal(t, "zone_auth", entry.Data["wapi_object"])
	assert.Contains(t, entry.Message, "INFOBLOX_WAPI_USER")

	assert.Equal(t, int64(1), *requests, "auth failures must not be retried")
	assertNoSecretsLogged(t, hook)
}

// TestRecordsLogsForbiddenFailure covers the read-only WAPI user from issue #50,
