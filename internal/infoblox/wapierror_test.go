// newStubGrid starts an HTTP server that answers every WAPI request with the
// given status code and body, and returns a Provider wired to a real
// infoblox-go-client connector pointed at it. The returned counter records how
// many HTTP requests the stub received, which is what pins the retry behaviour.
func newStubGrid(t *testing.T, status int, body string) (*Provider, *int64) {
	t.Helper()

	var requests int64
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		atomic.AddInt64(&requests, 1)
		w.WriteHeader(status)
		_, _ = w.Write([]byte(body))
	}))
	t.Cleanup(srv.Close)

	stubURL, err := url.Parse(srv.URL)
	require.NoError(t, err)

	hostCfg := ibclient.HostConfig{
		Scheme:  "http",
		Host:    stubURL.Hostname(),
		Port:    stubURL.Port(),
		Version: "2.3.1",
	}
	authCfg := ibclient.AuthConfig{Username: testWAPIUser, Password: testWAPIPassword}
	requestBuilder, err := ibclient.NewWapiRequestBuilder(hostCfg, authCfg)
	require.NoError(t, err)
	client, err := ibclient.NewConnector(hostCfg, authCfg,
		ibclient.NewTransportConfig("false", 5, 2), requestBuilder, NewAuthAwareRequestor(&ibclient.WapiHttpRequestor{}))
	require.NoError(t, err)

	return &Provider{
		client:       client,
		domainFilter: endpoint.NewDomainFilter([]string{"example.com"}),
		config:       &StartupConfig{View: "default", Username: testWAPIUser, Password: testWAPIPassword},
	}, &requests
}

// captureLogs installs a logrus test hook at debug level and returns it.
func captureLogs(t *testing.T) *logtest.Hook {
	t.Helper()
	previousLevel := log.GetLevel()
	log.SetLevel(log.DebugLevel)
	hook := logtest.NewGlobal()
	t.Cleanup(func() {
		hook.Reset()
		log.SetLevel(previousLevel)
	})
	return hook
}

// withInstantRetries removes the retry backoff so a retry test does not sleep.
func withInstantRetries(t *testing.T) {
	t.Helper()
	previous := retrySleep
	retrySleep = func(time.Duration) {}
	t.Cleanup(func() { retrySleep = previous })
}

// assertNoSecretsLogged fails the test if any captured log entry, in message or
// in any field value, contains the WAPI password or a basic-auth header.
func assertNoSecretsLogged(t *testing.T, hook *logtest.Hook) {
	t.Helper()
	for _, entry := range hook.AllEntries() {
		haystack := entry.Message
		for _, v := range entry.Data {
			haystack += fmt.Sprintf(" %v", v)
		}
		assert.NotContains(t, haystack, testWAPIPassword, "log entry leaked the WAPI password")
		assert.NotContains(t, strings.ToLower(haystack), "authorization:", "log entry leaked an Authorization header")
		assert.NotContains(t, strings.ToLower(haystack), "basic ", "log entry leaked basic auth credentials")
	}
}

func TestClassifyWAPIError(t *testing.T) {
	cases := []struct {
		name           string
		err            error
		expectedKind   WAPIFailureKind
		expectedStatus int
		retryable      bool
	}{
		{
			name:           "401 unauthorized is an auth failure",
			err:            errors.New("WAPI request error: 401('401 Unauthorized')\nContents:\n\n"),
			expectedKind:   WAPIFailureAuth,
			expectedStatus: http.StatusUnauthorized,
		},
		{
			name:           "403 forbidden is an auth failure",
			err:            errors.New("WAPI request error: 403('403 Forbidden')\nContents:\nAdmiss...\n"),
			expectedKind:   WAPIFailureAuth,
			expectedStatus: http.StatusForbidden,
		},
		{
			name:           "503 is transient and retryable",
			err:            errors.New("WAPI request error: 503('503 Service Temporarily Unavailable')\nContents:\n\n"),
			expectedKind:   WAPIFailureTransient,
			expectedStatus: http.StatusServiceUnavailable,
			retryable:      true,
		},
		{
			name:           "504 is transient and retryable",
			err:            errors.New("WAPI request error: 504('504 Gateway Timeout')"),
			expectedKind:   WAPIFailureTransient,
			expectedStatus: http.StatusGatewayTimeout,
			retryable:      true,
		},
		{
			name:           "wrapped NotFoundError stays not found",
			err:            fmt.Errorf("could not fetch object: %w", ibclient.NewNotFoundError("nope")),
			expectedKind:   WAPIFailureNotFound,
			expectedStatus: http.StatusNotFound,
		},
		{
			name:         "bare EOF from the grid master is transient",
			err:          errors.New(`Get "https://grid/wapi/v2.3.1/record:host?_proxy_search=GM": EOF`),
			expectedKind: WAPIFailureTransient,
			retryable:    true,
		},
		{
			name:         "client timeout is transient",
			err:          errors.New(`Get "https://grid/wapi/v2.3.1/record:a": context deadline exceeded`),
			expectedKind: WAPIFailureTransient,
			retryable:    true,
		},
		{
			name:           "400 bad request is neither auth nor transient",
			err:            errors.New("WAPI request error: 400('400 Bad Request')"),
			expectedKind:   WAPIFailureOther,
			expectedStatus: http.StatusBadRequest,
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			failure := ClassifyWAPIError(tc.err)
			assert.Equal(t, tc.expectedKind, failure.Kind)
			assert.Equal(t, tc.expectedStatus, failure.StatusCode)
			assert.Equal(t, tc.retryable, failure.Retryable())
		})
	}
}

func TestSanitizeWAPIReasonStripsCredentialsAndCollapsesLines(t *testing.T) {
	err := fmt.Errorf(`Get "https://%s:%s@grid.example.com/wapi/v2.3.1/record:a": WAPI request error: 401('401 Unauthorized')
Contents:
denied
`, testWAPIUser, testWAPIPassword)

	reason := SanitizeWAPIReason(err)

	assert.NotContains(t, reason, testWAPIPassword)
	assert.NotContains(t, reason, testWAPIUser)
	assert.NotContains(t, reason, "\n")
	assert.Contains(t, reason, "401")
}

